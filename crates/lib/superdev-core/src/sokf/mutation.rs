    #[test]
    fn a_service_edit_repairs_validates_and_reports_the_diff() {
        let original = "---\ntype: T\nid: alpha\n---\nOld body.\n";
        let repo = repo_with(original);
        let result = edit(
            &repo.path().join("knowledge"),
            repo.path(),
            EditRequest {
                path: "sokf:alpha".into(),
                edits: vec![ExactEdit {
                    old_text: "Old body.".into(),
                    new_text: "New body.".into(),
                }],
            },
            MutationPolicy::AgentSafe,
        )
        .unwrap();
        assert_eq!(result.validation, ValidationState::Valid);
        assert_eq!(result.resolved_path, "knowledge/a.md");
        assert_eq!(result.final_path, "knowledge/a.md");
        assert_eq!(result.changes.len(), 1);
        assert_eq!(result.changes[0].source, ChangeSource::Requested);
        assert_eq!(result.changes[0].path, "knowledge/a.md");
        assert!(result.changes[0].diff.contains("-Old body."));
        assert!(result.changes[0].diff.contains("+New body."));
    }

    #[test]
    fn requested_and_automatic_repair_diffs_stay_distinct() {
        let original =
            "---\ntype: T\nid: alpha\nlinks:\n  - rel: depends-on\n    to: beta\n---\nOld.\n";
        let repo = repo_with(original);
        fs::write(
            repo.path().join("knowledge/beta.md"),
            "---\ntype: T\nid: beta\n---\nBeta.\n",
        )
        .unwrap();
        let result = edit(
            &repo.path().join("knowledge"),
            repo.path(),
            EditRequest {
                path: "alpha".into(),
                edits: vec![ExactEdit {
                    old_text: "Old.".into(),
                    new_text: "See [beta](beta.md).".into(),
                }],
            },
            MutationPolicy::AgentSafe,
        )
        .unwrap();
        assert_eq!(result.validation, ValidationState::Valid);
        assert!(result.changes.iter().any(|change| {
            change.source == ChangeSource::Requested && change.path == "knowledge/a.md"
        }));
        assert!(result.changes.iter().any(|change| {
            change.source == ChangeSource::Repair
                && change.path == "knowledge/a.md"
                && change.diff.contains("[beta][sokf:beta]")
        }));
    }

